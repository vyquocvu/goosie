// DataTransfer holds the drag-and-drop payload and formats.
//
// It is the drag data store behind every DragEvent: scripts write entries with
// SetData during dragstart and read them back in drop. Formats keep insertion
// order so Types() reports what the author stored, in the order they stored it.
type DataTransfer struct {
	store         *DataTransferStore
	associated    bool
	dropEffect    string
	effectAllowed string
}

// DataTransferStore is the state shared by the short-lived DataTransfer views
// attached to each event in a single drag operation.
type DataTransferStore struct {
	data             map[string]string
	order            []string
	itemIDs          map[string]uint64
	nextItemID       uint64
	mode             DataTransferMode
	allowedEffects   string
	currentOperation string
}

// DataTransferMode controls which parts of the drag data store can be read or
// changed during a drag event. Script-created DataTransfer objects are
// read/write; browser-managed drag stores start protected.
type DataTransferMode uint8

const (
	DataTransferReadWrite DataTransferMode = iota
	DataTransferReadOnly
	DataTransferProtected
	DataTransferDisabled
)

// NewDataTransfer creates an empty DataTransfer object.
func NewDataTransfer() *DataTransfer {
	return &DataTransfer{
		store: &DataTransferStore{
			data:           make(map[string]string),
			itemIDs:        make(map[string]uint64),
			mode:           DataTransferReadWrite,
			allowedEffects: "none",
		},
		associated:    true,
		dropEffect:    "none",
		effectAllowed: "none",
	}
}

// NewDragDataTransfer creates the protected drag data store used by an
// ongoing user-agent drag operation.
func NewDragDataTransfer() *DataTransfer {
	return &DataTransfer{
		store: &DataTransferStore{
			data:             make(map[string]string),
			itemIDs:          make(map[string]uint64),
			mode:             DataTransferProtected,
			allowedEffects:   "uninitialized",
			currentOperation: "none",
		},
		associated:    true,
		dropEffect:    "none",
		effectAllowed: "uninitialized",
	}
}

// Mode reports the current drag data store access mode.
func (dt *DataTransfer) Mode() DataTransferMode {
	if dt == nil || !dt.associated || dt.store == nil {
		return DataTransferDisabled
	}
	return dt.store.mode
}

// SetMode changes access mode while the user agent dispatches a drag event.
func (dt *DataTransfer) SetMode(mode DataTransferMode) {
	if dt != nil && dt.store != nil {
		dt.store.mode = mode
	}
}

// StoreIdentity returns the identity shared by views of the same drag store.
func (dt *DataTransfer) StoreIdentity() *DataTransferStore {
	if dt == nil {
		return nil
	}
	return dt.store
}

// NewEventView creates a new DataTransfer object for one drag event.
func (dt *DataTransfer) NewEventView(eventType string, mode DataTransferMode) *DataTransfer {
	if dt == nil || dt.store == nil {
		return NewDataTransfer()
	}
	dt.store.mode = mode
	dropEffect := "none"
	switch eventType {
	case "drop", "dragend":
		dropEffect = dt.store.currentOperation
	case "dragenter", "dragover":
		dropEffect = defaultDropEffect(dt.store.allowedEffects)
	}
	return &DataTransfer{
		store:         dt.store,
		associated:    true,
		dropEffect:    dropEffect,
		effectAllowed: dt.store.allowedEffects,
	}
}

// Disassociate makes this event's DataTransfer object permanently detached
// from its drag store.
func (dt *DataTransfer) Disassociate() {
	if dt != nil {
		dt.associated = false
	}
}

func defaultDropEffect(effectAllowed string) string {
	switch effectAllowed {
	case "copy", "copyLink", "copyMove", "all", "uninitialized":
		return "copy"
	case "link", "linkMove":
		return "link"
	case "move":
		return "move"
	default:
		return "none"
	}
}

// StoreEffectAllowed records dragstart's post-dispatch allowed-effects state.
func (dt *DataTransfer) StoreEffectAllowed(effect string) {
	if dt != nil && dt.store != nil {
		dt.store.allowedEffects = effect
	}
}

// SetCurrentOperation records the operation selected by dragenter/dragover.
func (dt *DataTransfer) SetCurrentOperation(effect string) {
	if dt != nil && dt.store != nil {
		dt.store.currentOperation = effect
	}
}

// DragOperation returns the operation selected by a drop target when that
// operation is permitted by the source's effectAllowed value.
func DragOperation(effectAllowed, dropEffect string) string {
	switch dropEffect {
	case "copy":
		switch effectAllowed {
		case "uninitialized", "copy", "copyLink", "copyMove", "all":
			return "copy"
		}
	case "link":
		switch effectAllowed {
		case "uninitialized", "link", "copyLink", "linkMove", "all":
			return "link"
		}
	case "move":
		switch effectAllowed {
		case "uninitialized", "move", "copyMove", "linkMove", "all":
			return "move"
		}
	}
	return "none"
}

// CurrentOperation returns the operation selected by the latest dragenter or
// dragover event for this drag data store.
func (dt *DataTransfer) CurrentOperation() string {
	if dt == nil || dt.store == nil {
		return "none"
	}
	return dt.store.currentOperation
}

// normalizeFormat maps a data-transfer format to its canonical store key.
// Formats are case-insensitive; the legacy "text" and "url" keywords alias
// "text/plain" and "text/uri-list", respectively.
func normalizeFormat(format string) string {
	f := strings.ToLower(strings.Trim(format, "\t\n\f\r "))
	switch f {
	case "text":
		return "text/plain"
	case "url":
		return "text/uri-list"
	}
	return f
}

// SetData stores data for the given MIME type or format. An empty format is
// ignored, matching the spec's early return.
func (dt *DataTransfer) SetData(format, data string) {
	if dt.Mode() != DataTransferReadWrite {
		return
	}
	store := dt.store
	key := normalizeFormat(format)
	if key == "" {
		return
	}
	if store.data == nil {
		store.data = make(map[string]string)
	}
	if _, exists := store.data[key]; exists {
		dt.removeFormat(key)
	}
	store.data[key] = data
	store.order = append(store.order, key)
	if store.itemIDs == nil {
		store.itemIDs = make(map[string]uint64)
	}
	store.itemIDs[key] = store.newItemID()
}

// GetData retrieves data for the given MIME type or format, or "" when the
// format was never stored.
func (dt *DataTransfer) GetData(format string) string {
	if dt.Mode() == DataTransferDisabled || dt.Mode() == DataTransferProtected {
		return ""
	}
	if dt.store.data == nil {
		return ""
	}
	key := normalizeFormat(format)
	data, exists := dt.store.data[key]
	if !exists && strings.HasPrefix(key, "text/uri-list;") {
		// MIME parameters do not opt into the legacy URL conversion. Resolve
		// the URI-list item while returning its original, unparsed payload.
		data = dt.store.data["text/uri-list"]
	}
	if strings.EqualFold(strings.Trim(format, "\t\n\f\r "), "url") {
		return firstURIListEntry(data)
	}
	return data
}

func firstURIListEntry(data string) string {
	for _, line := range strings.Split(data, "\n") {
		line = strings.TrimSpace(strings.TrimSuffix(line, "\r"))
		if line != "" && !strings.HasPrefix(line, "#") {
			return line
		}
	}
	return ""
}

// ClearData removes stored data for the given format, or all data if no format given.
func (dt *DataTransfer) ClearData(format ...string) {
	if dt.Mode() != DataTransferReadWrite || dt.store.data == nil {
		return
	}
	if len(format) == 0 {
		clear(dt.store.data)
		clear(dt.store.itemIDs)
		dt.store.order = nil
		return
	}
	key := normalizeFormat(format[0])
	dt.removeFormat(key)
}

func (dt *DataTransfer) removeFormat(key string) {
	delete(dt.store.data, key)
	delete(dt.store.itemIDs, key)
	for i, t := range dt.store.order {
		if t == key {
			dt.store.order = append(dt.store.order[:i], dt.store.order[i+1:]...)
			break
		}
	}
}

// HasFormat reports whether a string item with the given format is present.
func (dt *DataTransfer) HasFormat(format string) bool {
	if dt == nil || dt.store == nil {
		return false
	}
	_, ok := dt.store.data[normalizeFormat(format)]
	return ok
}

// AddStringItem appends a DataTransferItemList string entry using its literal
// lowercased type string. It returns false when the mode forbids mutation or
// that type is already present.
func (dt *DataTransfer) AddStringItem(format, data string) bool {
	if dt.Mode() != DataTransferReadWrite {
		return false
	}
	store := dt.store
	key := strings.ToLower(format)
	if key == "" || dt.HasTypeString(key) {
		return false
	}
	if store.data == nil {
		store.data = make(map[string]string)
	}
	if store.itemIDs == nil {
		store.itemIDs = make(map[string]uint64)
	}
	store.data[key] = data
	store.order = append(store.order, key)
	store.itemIDs[key] = store.newItemID()
	return true
}

// HasTypeString reports whether an item with this literal type string exists,
// without applying the legacy SetData/getData aliases.
func (dt *DataTransfer) HasTypeString(format string) bool {
	if dt == nil || dt.store == nil {
		return false
	}
	_, ok := dt.store.data[strings.ToLower(format)]
	return ok
}

// ItemID returns the identity of a live string item with the given type.
func (dt *DataTransfer) ItemID(format string) (uint64, bool) {
	if dt == nil || dt.store == nil || !dt.HasTypeString(format) {
		return 0, false
	}
	id := dt.store.itemIDs[strings.ToLower(format)]
	return id, id != 0
}

// HasItemID reports whether an item with this literal type and identity is
// still present in the shared drag data store.
func (dt *DataTransfer) HasItemID(format string, id uint64) bool {
	current, ok := dt.ItemID(format)
	return ok && current == id
}

func (store *DataTransferStore) newItemID() uint64 {
	store.nextItemID++
	if store.nextItemID == 0 {
		store.nextItemID++
	}
	return store.nextItemID
}

// RemoveStringItem removes an item by its literal type string.
func (dt *DataTransfer) RemoveStringItem(format string) {
	if dt.Mode() == DataTransferReadWrite {
		dt.removeFormat(strings.ToLower(format))
	}
}

// Types returns the list of formats currently stored in the DataTransfer, in
// insertion order.
func (dt *DataTransfer) Types() []string {
	if dt.Mode() == DataTransferDisabled || len(dt.store.order) == 0 {
		return nil
	}
	types := make([]string, len(dt.store.order))
	copy(types, dt.store.order)
	return types
}

// DropEffect returns the drag operation shown at the cursor: "none", "copy",
// "move" or "link".
func (dt *DataTransfer) DropEffect() string { return dt.dropEffect }

// SetDropEffect records the operation a drop target would perform. Values
// outside the enumerated set are ignored, matching the spec's enumerated setter.
func (dt *DataTransfer) SetDropEffect(effect string) {
	switch effect {
	case "none", "copy", "move", "link":
		dt.dropEffect = effect
	}
}

// EffectAllowed returns the operations the drag source permits: "none", "copy",
// "copyLink", "copyMove", "link", "linkMove", "move", "all" or "uninitialized".
func (dt *DataTransfer) EffectAllowed() string { return dt.effectAllowed }

// SetEffectAllowed restricts which drop effects a target may choose. Values
