// funcEqual reports whether two function values refer to the same function.
// Go does not allow direct comparison of function values with ==, so we
// compare their code pointers via reflect.
func funcEqual(a, b func(*Event)) bool {
	return reflect.ValueOf(a).Pointer() == reflect.ValueOf(b).Pointer()
}

// EventPhase identifies the current phase of event propagation.
type EventPhase int

const (
	NonePhase EventPhase = iota
	CapturingPhase
	AtTarget
	BubblingPhase
)

// Event is a DOM event. It carries a type, propagation state, and references
// to the target and current-target nodes.
type Event struct {
	Type              string
	target            *Node
	currentTarget     *Node
	phase             EventPhase
	bubbles           bool
	cancelable        bool
	isTrusted         bool
	interfaceName     string
	persisted         bool
	defaultPrevented  bool
	inPassiveListener bool
	stopped           bool // stopPropagation called
	immediateStopped  bool // stopImmediatePropagation called
	timeStamp         time.Time

	// payload points at the concrete subtype (e.g. *KeyboardEvent) that embeds
	// this Event. Listeners and dispatch only ever pass *Event, so a type
	// assertion on that pointer cannot recover the subtype; this back-pointer is
	// how the JS bridge reads key/mouse fields. Constructors that build a
	// subtype set it; a plain NewEvent leaves it nil.
	payload any
}

// NewEvent creates a new Event with the given type and options.
func NewEvent(typ string, bubbles, cancelable bool) *Event {
	return &Event{
		Type:          typ,
		bubbles:       bubbles,
		cancelable:    cancelable,
		interfaceName: "Event",
		timeStamp:     time.Now(),
	}
}

// NewTrustedEvent creates an event generated by user-agent behavior rather
// than by page script. Events constructed by script continue to use NewEvent
// and report isTrusted=false.
func NewTrustedEvent(typ string, bubbles, cancelable bool) *Event {
	e := NewEvent(typ, bubbles, cancelable)
	e.isTrusted = true
	return e
}

// NewPageTransitionEvent creates a trusted pageshow/pagehide-family event.
func NewPageTransitionEvent(typ string, bubbles, cancelable, persisted bool) *Event {
	e := NewTrustedEvent(typ, bubbles, cancelable)
	e.interfaceName = "PageTransitionEvent"
	e.persisted = persisted
	return e
}

// IsTrusted reports whether the event was generated by the user agent.
func (e *Event) IsTrusted() bool { return e.isTrusted }

// InterfaceName is the Web IDL interface brand exposed by string conversion.
func (e *Event) InterfaceName() string {
	if e.interfaceName == "" {
		return "Event"
	}
	return e.interfaceName
}

// Persisted reports whether a PageTransitionEvent represents a persisted
// page-cache transition.
func (e *Event) Persisted() bool { return e.persisted }

// StopPropagation prevents further propagation of the event.
func (e *Event) StopPropagation() {
	e.stopped = true
}

// StopImmediatePropagation prevents further propagation and any other
// listeners on the same target from firing.
func (e *Event) StopImmediatePropagation() {
	e.stopped = true
	e.immediateStopped = true
}

// PreventDefault marks the event as cancelled, preventing the default action.
func (e *Event) PreventDefault() {
	if e.cancelable && !e.inPassiveListener {
		e.defaultPrevented = true
	}
}

// SetInPassiveListener controls whether preventDefault is ignored for the
// duration of a passive listener callback.
func (e *Event) SetInPassiveListener(passive bool) { e.inPassiveListener = passive }

// InPassiveListener reports whether the current callback is passive.
func (e *Event) InPassiveListener() bool { return e.inPassiveListener }

// SetTarget assigns the target before listeners run. The engine uses this for
// the Window capture step, which precedes the node dispatcher.
func (e *Event) SetTarget(target *Node) { e.target = target }

// Target returns the node to which the event was originally dispatched.
func (e *Event) Target() *Node { return e.target }

// CurrentTarget returns the node whose listeners are currently being invoked.
func (e *Event) CurrentTarget() *Node { return e.currentTarget }

// Phase returns the current propagation phase.
func (e *Event) Phase() EventPhase { return e.phase }

// Bubbles reports whether the event bubbles up through the tree.
func (e *Event) Bubbles() bool { return e.bubbles }

// Cancelable reports whether the event's default action can be prevented.
func (e *Event) Cancelable() bool { return e.cancelable }

// DefaultPrevented reports whether PreventDefault was called.
func (e *Event) DefaultPrevented() bool { return e.defaultPrevented }

// PropagationStopped reports whether a listener called stopPropagation (or
// stopImmediatePropagation) part-way through dispatch. The binding needs it to
// decide whether the window step of the path still runs: `window` is not a
// *dom.Node, so dom.DispatchEvent stops at the document and the caller appends
// the window step itself - and must not append it when propagation stopped.
func (e *Event) PropagationStopped() bool { return e.stopped }

// ClearPropagationFlags resets the dispatch-only propagation state after the
// complete event path, including any Window step, has finished.
func (e *Event) ClearPropagationFlags() {
	e.stopped = false
	e.immediateStopped = false
}

// TimeStamp returns the time at which the event was created.
func (e *Event) TimeStamp() time.Time { return e.timeStamp }

