package paint

var bidiMirror = map[rune]rune{
	'(': ')', ')': '(',
	'[': ']', ']': '[',
	'{': '}', '}': '{',
	'<': '>', '>': '<',
	'«': '»', '»': '«',
	'‹': '›', '›': '‹',
	'⟨': '⟩', '⟩': '⟨',
	'⟪': '⟫', '⟫': '⟪',
	'⟬': '⟭', '⟭': '⟬',
	'⟮': '⟯', '⟯': '⟮',
	'「': '」', '」': '「',
	'『': '』', '』': '『',
	'【': '】', '】': '【',
	'〔': '〕', '〕': '〔',
	'〖': '〗', '〗': '〖',
	'〘': '〙', '〙': '〘',
	'〚': '〛', '〛': '〚',
	'（': '）', '）': '（',
	'［': '］', '］': '［',
	'｛': '｝', '｝': '｛',
	'＜': '＞', '＞': '＜',
	'｟': '｠', '｠': '｟',
	'⌈': '⌉', '⌉': '⌈',
	'⌊': '⌋', '⌋': '⌊',
}

func mirrorRune(r rune, level byte) rune {
	if level&1 == 0 {
		return r
	}
	if m, ok := bidiMirror[r]; ok {
		return m
	}
	return r
}
